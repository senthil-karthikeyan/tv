package store

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"sort"
	"sync"
	"time"

	"tv/internal/model"
)

// ErrNotFound is returned by store operations when the requested resource does not exist.
var ErrNotFound = errors.New("not found")

// SceneStore is a concurrency-safe in-memory store for Scene entities.
type SceneStore struct {
	mu     sync.RWMutex
	scenes map[string]*model.Scene
}

// NewSceneStore creates a SceneStore and pre-populates it with default navigation scenes.
func NewSceneStore() *SceneStore {
	s := &SceneStore{scenes: make(map[string]*model.Scene)}
	s.seed()
	return s
}

// NewEmptySceneStore creates a SceneStore with no pre-populated data.
// Intended for use in tests that need a clean starting state.
func NewEmptySceneStore() *SceneStore {
	return &SceneStore{scenes: make(map[string]*model.Scene)}
}

// seed inserts the default launcher navigation scenes.
// Called only from NewSceneStore before the store is shared across goroutines,
// so no mutex is needed here.
func (s *SceneStore) seed() {
	now := time.Now().UTC()
	defaults := []model.CreateSceneRequest{
		{Name: "Home", Label: "home", Icon: "home", Route: "/dashboard", Order: 1, Visible: true},
		{Name: "Users", Label: "users", Icon: "people", Route: "/users", Order: 2, Visible: true},
		{Name: "Settings", Label: "settings", Icon: "settings", Route: "/settings", Order: 3, Visible: true},
	}
	for _, req := range defaults {
		id := mustGenerateID()
		s.scenes[id] = &model.Scene{
			ID:        id,
			Name:      req.Name,
			Label:     req.Label,
			Icon:      req.Icon,
			Route:     req.Route,
			Order:     req.Order,
			Visible:   req.Visible,
			CreatedAt: now,
			UpdatedAt: now,
		}
	}
}

// List returns copies of all scenes ordered by Order ascending.
func (s *SceneStore) List() []*model.Scene {
	s.mu.RLock()
	defer s.mu.RUnlock()

	out := make([]*model.Scene, 0, len(s.scenes))
	for _, sc := range s.scenes {
		cp := *sc
		out = append(out, &cp)
	}
	sort.Slice(out, func(i, j int) bool {
		return out[i].Order < out[j].Order
	})
	return out
}

// Get returns a copy of the scene identified by id, or ErrNotFound.
func (s *SceneStore) Get(id string) (*model.Scene, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()

	sc, ok := s.scenes[id]
	if !ok {
		return nil, ErrNotFound
	}
	cp := *sc
	return &cp, nil
}

// Create persists a new scene built from req and returns a copy of the stored record.
// The ID and timestamps are generated by the store; any client-supplied values are ignored.
func (s *SceneStore) Create(req *model.CreateSceneRequest) (*model.Scene, error) {
	id, err := generateID()
	if err != nil {
		return nil, err
	}
	now := time.Now().UTC()
	sc := &model.Scene{
		ID:        id,
		Name:      req.Name,
		Label:     req.Label,
		Icon:      req.Icon,
		Route:     req.Route,
		Order:     req.Order,
		Visible:   req.Visible,
		CreatedAt: now,
		UpdatedAt: now,
	}

	s.mu.Lock()
	s.scenes[id] = sc
	s.mu.Unlock()

	cp := *sc
	return &cp, nil
}

// Update applies non-nil fields from req to the scene identified by id,
// advances UpdatedAt, and returns the updated copy. Returns ErrNotFound if the id
// does not exist.
func (s *SceneStore) Update(id string, req *model.UpdateSceneRequest) (*model.Scene, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	sc, ok := s.scenes[id]
	if !ok {
		return nil, ErrNotFound
	}

	if req.Name != nil {
		sc.Name = *req.Name
	}
	if req.Label != nil {
		sc.Label = *req.Label
	}
	if req.Icon != nil {
		sc.Icon = *req.Icon
	}
	if req.Route != nil {
		sc.Route = *req.Route
	}
	if req.Order != nil {
		sc.Order = *req.Order
	}
	if req.Visible != nil {
		sc.Visible = *req.Visible
	}
	sc.UpdatedAt = time.Now().UTC()

	cp := *sc
	return &cp, nil
}

// Delete removes the scene identified by id. Returns ErrNotFound if it does not exist.
func (s *SceneStore) Delete(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	if _, ok := s.scenes[id]; !ok {
		return ErrNotFound
	}
	delete(s.scenes, id)
	return nil
}

// generateID creates a random 16-character hex string using crypto/rand.
func generateID() (string, error) {
	b := make([]byte, 8)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// mustGenerateID generates an ID and panics on failure. Used only during seeding at startup.
func mustGenerateID() string {
	id, err := generateID()
	if err != nil {
		panic("scene store seed: failed to generate ID: " + err.Error())
	}
	return id
}
